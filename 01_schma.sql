-- =================================================================
-- Description: Database tables for Banks, Terminals, and Audit Logs
-- =================================================================

-- 1. Banks Table
CREATE TABLE banks (
    bank_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_code VARCHAR2(10) UNIQUE NOT NULL,
    bank_name VARCHAR2(100) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'TERMINATED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Added Services Table
CREATE TABLE payment_services (
    service_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_code VARCHAR2(20) UNIQUE NOT NULL,
    service_name VARCHAR2(100) NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'TERMINATED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Terminals Table (POS / ATM / Online Gateway)
CREATE TABLE terminals (
    terminal_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_sn VARCHAR2(50) UNIQUE NOT NULL,
    bank_id NUMBER REFERENCES banks(bank_id),
    terminal_type VARCHAR2(20) CHECK (terminal_type IN ('POS', 'ATM','WEB_GATEWAY')),
    status VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'TERMINATED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Audit Trail Log Table
CREATE TABLE audit_logs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type VARCHAR2(50) NOT NULL,
    entity_name VARCHAR2(50) NOT NULL,
    entity_id NUMBER,
    detailes VARCHAR2(4000),
    performed_by VARCHAR2(50) DEFAULT USER,
    action_timestamp TIMESTAMP DEFAULT  CURRENT_TIMESTAMP
);
